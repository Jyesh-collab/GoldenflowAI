import pytest
from appium.webdriver.common.appiumby import AppiumBy
from pages.browse_pages import HomeScreen, ProductDetailScreen
from pages.checkout_pages import CartScreen, DeliveryAddressScreen, PaymentMethodScreen


@pytest.mark.goldenflow
@pytest.mark.generated
@pytest.mark.critical
def test_home_to_payment_failure(driver):
    """
    Home to Payment Failure
    
    Generated by GoldenFlow from production telemetry.
    Journey aj_007: 72 sessions (4.8% of traffic), score 72.5, 15 failure signal(s) observed.
    Locators from: crawl, page_object.
    """
    # Home
    home = HomeScreen(driver)
    home.open_search()

    # Product Detail
    product_detail = ProductDetailScreen(driver)
    product_detail.select_variant()

    # Cart
    cart = CartScreen(driver)
    cart.increase_quantity()
    # TODO tighten: GoldenFlow cannot infer the expected count from telemetry
    assert cart.item_count() >= 0, "Cart is reachable and populated"

    # Delivery Address
    delivery_address = DeliveryAddressScreen(driver)
    delivery_address.select_saved_address()
    assert driver.find_element(AppiumBy.ACCESSIBILITY_ID, "address_add_new").is_displayed(), \
        "Delivery Address is reachable and populated"

    # Payment Method
    payment_method = PaymentMethodScreen(driver)
    payment_method.choose_card()
    assert driver.find_element(AppiumBy.ACCESSIBILITY_ID, "payment_continue").is_displayed(), \
        "Payment Method is reachable and populated"

    # Payment Failure
    payment_failure = driver.find_element(AppiumBy.ACCESSIBILITY_ID, "payment_failure_icon")
    assert payment_failure.is_displayed(), "Payment Failure is reachable and populated"
